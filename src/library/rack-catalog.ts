export function createRackFromTemplate(template: RackTemplate, x = 300, y = 100, customName?: string): RackData {
  return {
    id: generateId(),
    name: customName || template.name,
    units: template.units,
    x,
    y,
    rackWidth: template.rackWidth,
    depthMm: template.depthMm,
    rackType: template.rackType,
    frontDoor: template.frontDoor,
    sidePanels: template.sidePanels,
    rackColor: template.rackColor,
    mounting: template.mounting,
    leftCableManagerWidth: template.leftCableManagerWidth,
    rightCableManagerWidth: template.rightCableManagerWidth,
    vcmType: template.vcmType,
    showPduLeft: true,
    showPduRight: true,
  };
}
